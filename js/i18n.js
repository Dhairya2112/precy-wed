translations.gu = translations.en;

class I18nManager {
  constructor() {
    this.currentLang = 'en';
  }

  initLanguage() {
    this.currentLang = 'en';
    localStorage.setItem('precy_het_lang', 'en');
    this.applyTranslations('en');
  }

  getCurrentLang() {
    return 'en';
  }

  setLanguage(lang) {
    this.currentLang = 'en';
    localStorage.setItem('precy_het_lang', 'en');
    this.applyTranslations('en');
  }

  toggleLanguage() {
    this.applyTranslations('en');
    return 'en';
  }

  t(key) {
    const dict = translations.en;
    return dict[key] !== undefined ? dict[key] : key;
  }

  applyTranslations(lang = 'en') {
    const dict = translations.en;
    if (!dict) return;

    const elements = document.querySelectorAll('[data-i18n]');
    elements.forEach(el => {
      const key = el.getAttribute('data-i18n');
      if (dict[key] !== undefined && dict[key] !== '') {
        const val = dict[key];
        if (val.includes('\n')) {
          el.innerHTML = val.replace(/\n/g, '<br>');
        } else {
          el.textContent = val;
        }
      }
    });

    document.documentElement.lang = 'en';
    document.documentElement.classList.add('lang-en');
    document.documentElement.classList.remove('lang-gu');

    window.dispatchEvent(new CustomEvent('languagechange', { detail: { lang: 'en' } }));
  }
}

window.i18n = new I18nManager();
